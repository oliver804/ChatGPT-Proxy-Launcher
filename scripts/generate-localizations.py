#!/usr/bin/env python3
"""Generate typed Swift/C# catalogs from reviewed, ordered UTF-8 translation files."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "Resources" / "i18n"
LANGUAGES = {
    "zh-Hant": ("traditionalChinese", "zh-TW"),
    "ru": ("russian", "ru"),
    "fa": ("persian", "fa"),
    "be": ("belarusian", "be"),
    "es": ("spanish", "es"),
    "ar": ("arabic", "ar"),
    "pt": ("portuguese", "pt"),
}


def mac_keys():
    source = (ROOT / "Sources" / "Localization.swift").read_text()
    matches = re.findall(r'^        ("(?:\\.|[^"\\])*"): ("(?:\\.|[^"\\])*"),?$', source, re.M)
    assert len(matches) > 90, "Could not read macOS source catalog"
    return [json.loads(key) for key, _ in matches]


def windows_keys():
    source = (ROOT / "Windows" / "App" / "Strings.cs").read_text()
    keys = re.findall(r'\["([^"]+)"\]\s*=\s*\("(?:\\.|[^"\\])*",\s*"(?:\\.|[^"\\])*"\)', source)
    assert len(keys) > 45, "Could not read Windows source catalog"
    return keys


def read_catalog(platform, language, keys):
    path = DATA / f"{platform}-{language}.txt"
    lines = path.read_text(encoding="utf-8").splitlines()
    assert len(lines) == len(keys), f"{path}: expected {len(keys)} messages, got {len(lines)}"
    result = {}
    for key, raw in zip(keys, lines):
        value = raw.replace(r"\n", "\n")
        assert value.strip(), f"Empty translation of {key} in {path}"
        if platform == "mac":
            assert key.count("%@") == value.count("%@"), f"Placeholder mismatch: {key} in {path}"
        else:
            source = (ROOT / "Windows" / "App" / "Strings.cs").read_text()
            match = re.search(r'\["' + re.escape(key) + r'"\]\s*=\s*\("((?:\\.|[^"\\])*)"', source)
            assert match
            assert sorted(re.findall(r"\{\d+\}", match.group(1))) == sorted(re.findall(r"\{\d+\}", value)), f"Placeholder mismatch: {key} in {path}"
        result[key] = value
    return result


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def generated_files():
    mac = mac_keys()
    windows = windows_keys()
    swift = ["// Generated by scripts/generate-localizations.py. Edit Resources/i18n/*.txt instead.",
             "enum AdditionalTranslations {", "    static let values: [AppLanguage: [String: String]] = ["]
    csharp = ["// Generated by scripts/generate-localizations.py. Edit Resources/i18n/*.txt instead.",
              "namespace LocalRouteLauncher;", "",
              "public static class AdditionalStrings", "{", "    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> Values =",
              "        new Dictionary<string, IReadOnlyDictionary<string, string>>", "        {"]
    for code, (swift_case, windows_code) in LANGUAGES.items():
        swift.append(f"        .{swift_case}: [")
        for key, value in read_catalog("mac", code, mac).items():
            swift.append(f"            {quoted(key)}: {quoted(value)},")
        swift.append("        ],")
        csharp.append(f"            [{quoted(windows_code)}] = new Dictionary<string, string>")
        csharp.append("            {")
        for key, value in read_catalog("windows", windows_code, windows).items():
            csharp.append(f"                [{quoted(key)}] = {quoted(value)},")
        csharp.append("            },")
    swift += ["    ]", "}", ""]
    csharp += ["        };", "}", ""]
    return {
        ROOT / "Sources" / "AdditionalTranslations.swift": "\n".join(swift),
        ROOT / "Windows" / "App" / "AdditionalStrings.cs": "\n".join(csharp),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            assert path.is_file() and path.read_text() == expected, f"Regenerate {path}"
        else:
            path.write_text(expected)
        print(f"PASS: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
